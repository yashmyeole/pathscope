"""Render data/stats/phase1_leakage_report.md from the split_v1 outputs. Script-generated so the
numbers in the report can never drift from the manifests (guide, Phase 7)."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from pathscope.data.split import SPLIT_DIR


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "–"


def render_report(split_dir: Path = SPLIT_DIR) -> str:
    s = json.loads((split_dir / "summary.json").read_text())
    q = pd.read_parquet(split_dir / "queries_all_flags.parquet")
    d = pd.read_parquet(split_dir / "dev_all_flags.parquet")
    c = pd.read_parquet(split_dir / "corpus.parquet")
    manual = pd.read_csv(split_dir / "manual_near_dups.csv")
    cfg = s["queries_test"]["config"]
    t, v = s["queries_test"], s["dev_validation"]
    w = s["corpus"]["within_corpus"]

    L: list[str] = []
    L += ["# Phase 1 — Data split and leakage report", ""]
    L += [
        "Generated by `pathscope leakage-report` from `data/manifests/split_v1/summary.json`. "
        "Re-run `pathscope split && pathscope leakage-report` to regenerate.",
        "",
        "## Split",
        "",
        "| Role | Source | Images | Text used as caption |",
        "|---|---|---|---|",
        f"| **Queries** (scored) | PathVQA test | {t['n_queries']} → **{t['clean']} clean** | pseudo-caption from Q/A |",
        f"| **Dev** (prompt tuning only) | PathVQA validation | {v['n_queries']} → **{v['clean']} clean** | pseudo-caption from Q/A |",
        f"| **Corpus** (retrieved from) | PathVQA train + ARCH books + ARCH PubMed | **{s['corpus']['rows']:,}** | pseudo-caption / ARCH caption |",
        "",
        "Corpus by source: "
        + ", ".join(f"{k} {n:,}" for k, n in s["corpus"]["by_source"].items())
        + f". Exact duplicates removed inside the corpus: {w['exact_duplicate_rows_removed']} "
        f"({', '.join(f'{k} {n}' for k, n in w['exact_duplicates_by_source_pair'].items())}); "
        f"near-duplicate pairs still inside the corpus at d ≤ {w['phash_threshold']}: "
        f"{w['near_duplicate_pairs_remaining']} (reported, not removed — multi-panel ARCH figures "
        "are legitimately alike).",
        "",
        "Why this split: PathVQA questions were auto-generated from textbook captions, so the test "
        "split is the only place we have both an image *and* text we can score claims against. "
        "ARCH is corpus-only because it has real captions but no held-out question set. "
        "Validation is reserved for tuning the Phase 4 prompts so the test numbers are reported "
        "on data the prompts never saw.",
        "",
        "## The three leakage checks",
        "",
        "| Check | What it catches | Test queries flagged | Dev flagged |",
        "|---|---|---|---|",
        f"| 1. Exact (pixel MD5) | identical decoded pixels | {t['exact']['n']} ({t['exact']['pct']}%) | {v['exact']['n']} ({v['exact']['pct']}%) |",
        f"| 2. Near (pHash ≤ {cfg['phash_threshold']} + reviewed grey zone) | re-encoded / rescaled / cropped copies | {t['near']['n']} ({t['near']['pct']}%) | {v['near']['n']} ({v['near']['pct']}%) |",
        f"| 3. Text (longest fragment, ≥{cfg['text_min_words']} words, token_sort_ratio ≥ {cfg['text_threshold']:.0f}) | same figure / same case caption in the corpus | {t['text']['n']} ({t['text']['pct']}%) | {v['text']['n']} ({v['text']['pct']}%) |",
        f"| **Any** | | **{t['any']['n']} ({t['any']['pct']}%)** | **{v['any']['n']} ({v['any']['pct']}%)** |",
        f"| Dev images that are siblings of a test image (removed from dev) | | – | {v['leaked_vs_test']} ({v['leaked_vs_test_only']} not already flagged) |",
        "",
        f"**Shrinkage:** test {t['n_queries']} → {t['clean']} ({t['shrinkage_pct']}%), "
        f"dev {v['n_queries']} → {v['clean']} ({v['shrinkage_pct']}%).",
        "",
    ]

    # Where do the leaks come from?
    near_src = q[q.near_dup].phash_match.map(lambda m: m.get("source")).value_counts().to_dict()
    text_src = q[q.text_dup].text_match.map(lambda m: m.get("source")).value_counts().to_dict()
    L += [
        "### Where the leaks come from",
        "",
        f"Near-duplicate matches for test queries by corpus source: {near_src}. "
        f"Text matches by corpus source: {text_src}. ",
        "",
        "**Every flagged pair is PathVQA-test ↔ PathVQA-train.** ARCH shares no image and no caption "
        "with PathVQA on any of the three checks — the two datasets come from different books and "
        "articles. So the leakage problem the guide warned about is real, but it is entirely internal "
        "to PathVQA's own split, which was evidently done at the Q/A-row level rather than the figure "
        "level.",
        "",
    ]

    # pHash threshold justification
    gz = t["near"]["grey_zone"]
    hist = pd.concat([q.phash_dist, d.phash_dist]).value_counts(
        bins=[-1, 24, 48, 58, 70, 86, 100, 256], sort=False
    )
    L += [
        "### How the pHash threshold was chosen",
        "",
        "16×16 DCT pHash → 256 bits; distance is Hamming. Every query/corpus nearest pair with "
        "d ≤ 86 was rendered and inspected by eye (`data/stats/contact_sheets/phase1_phash_pairs_part1..4.png`):",
        "",
        "| Distance band | Pairs (test+dev) | Verdict |",
        "|---|---|---|",
    ]
    verdicts = {
        "(-1.001, 24.0]": "all the same photograph",
        "(24.0, 48.0]": "all the same photograph (crops, colour shifts)",
        "(48.0, 58.0]": "all the same photograph",
        "(58.0, 70.0]": "mixed — grey zone, adjudicated by hand",
        "(70.0, 86.0]": "mostly different; a few same (twins d=80, adrenal d=84)",
        "(86.0, 100.0]": "different — chance level for 256-bit hashes",
        "(100.0, 256.0]": "different",
    }
    for iv, n in hist.items():
        L.append(f"| {iv} | {n} | {verdicts.get(str(iv), '')} |")
    L += [
        "",
        f"Automatic threshold **d ≤ {cfg['phash_threshold']}** (zero false positives observed). "
        f"Grey zone {gz['range'][0]}–{gz['range'][1]}: {gz['n_pairs']} test pairs reviewed "
        f"({gz['n_same']} same, {gz['n_different']} different); "
        f"dev: {v['near']['grey_zone']['n_same']} same, {v['near']['grey_zone']['n_different']} different. "
        "Verdicts live in `manual_near_dups.csv` and are applied by `pathscope split`. "
        "The usual 'd ≤ 10' rule of thumb would have missed ~80% of the true duplicates here, "
        "because PathVQA's duplicates are re-photographed / re-cropped textbook figures, not byte-level copies.",
        "",
        "Sensitivity (test queries at or below d): "
        + ", ".join(f"d≤{k}: {n}" for k, n in t["near"]["n_at_or_below"].items())
        + ".",
        "",
    ]

    # text check justification + examples
    L += [
        "### How the text check was designed",
        "",
        "First attempt — `token_set_ratio` on the whole joined pseudo-caption — flagged 39% of test "
        "queries, almost all of them short diagnosis labels (`skin; skin kaposis sarcoma`) that two "
        "*different* images legitimately share. Removing those would strip out exactly the queries "
        "where retrieval has a chance to work and bias TCR downward. So the check is split in two:",
        "",
        f"* **Removed:** the query's longest gold fragment has ≥ {cfg['text_min_words']} words and "
        f"matches a corpus text at `token_sort_ratio` ≥ {cfg['text_threshold']:.0f}. These are the "
        "same figure legend or the same case photographed from another angle.",
        f"* **Kept, flagged `label_match`:** a short label identical to a corpus text — "
        f"{t['label_match_kept']['n']} test queries ({t['label_match_kept']['pct']}%). This becomes a "
        "stratification variable in Phase 4: TCR for queries whose exact diagnosis has a corpus exemplar "
        "vs. those without.",
        "",
        "Sensitivity of the removed set to the minimum-words rule (test, score ≥ threshold): "
        + ", ".join(f"≥{k} words: {n}" for k, n in t["text"]["sensitivity_min_words"].items())
        + "; to the score threshold (≥6 words): "
        + ", ".join(f"≥{k}: {n}" for k, n in t["text"]["n_at_or_above"].items())
        + ". The distribution is bimodal (identical or not), so the choice of 85 vs 95 moves <10 queries.",
        "",
        "Examples of removed text matches:",
        "",
        "| score | query longest fragment | corpus text |",
        "|---|---|---|",
    ]
    ex = q[q.text_dup].sort_values("text_score").iloc[:: max(1, q.text_dup.sum() // 6)].head(6)
    for r in ex.itertuples():
        L.append(
            f"| {r.text_score:.0f} | {r.text_key[:70]} | {r.text_match.get('corpus_text', '')[:70]} |"
        )
    L += ["", "Examples of kept label matches:", "", "| query label | corpus text |", "|---|---|"]
    for r in q[q.label_match].head(5).itertuples():
        L.append(f"| {r.text_key[:60]} | {r.label_match_desc.get('corpus_text', '')[:60]} |")

    # composition of clean sets
    qc = pd.read_parquet(split_dir / "queries.parquet")
    L += [
        "",
        "## Clean query set at a glance",
        "",
        f"{len(qc)} test images; {int(qc.label_match.sum())} with a label match in the corpus; "
        f"median pseudo-caption length {int(qc.text.str.split().str.len().median())} words; "
        f"{int((qc.text == '').sum())} with empty gold text (kept, will be excluded from TCR by construction).",
        "",
        "Corpus text length: ARCH captions median "
        f"{int(c[c.source.str.startswith('arch')].text.str.split().str.len().median())} words vs "
        f"PathVQA-train pseudo-captions median {int(c[c.source == 'pathvqa_train'].text.str.split().str.len().median())} words. "
        "Phase 3/4 should report by corpus source — ARCH neighbours will carry roughly 3× more claims each.",
        "",
        "## Files",
        "",
        "```",
        "data/manifests/split_v1/",
        "  queries.parquet            clean test queries (one row per image, with flags)",
        "  dev.parquet                clean validation images for prompt tuning",
        "  corpus.parquet             10k corpus images: source, image_id, text, member/row_idx to load",
        "  queries_all_flags.parquet  every test image with all signals, for audit",
        "  dev_all_flags.parquet      same for validation",
        "  manual_near_dups.csv       grey-zone adjudications (who, when, verdict, note)",
        "  summary.json               every number in this report",
        "```",
        "",
        f"_{len(manual)} grey-zone pairs reviewed; reviewer and date recorded per row._",
        "",
    ]
    return "\n".join(L)
